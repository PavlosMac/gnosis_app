// Generates src/lib/legal-registry.generated.ts: a static import map of every
// dated legal document, so the bundler (Turbopack) sees literal import() paths
// and the standalone production image needs no src/content directory at runtime.
//
// Runs before dev, build and test (see package.json). "Add a dated .mdx file,
// edit nothing else" holds because this file is regenerated, never hand-edited.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contentDir = path.join(root, "src/content/legal");
const outFile = path.join(root, "src/lib/legal-registry.generated.ts");

const DOCUMENT_IDS = ["terms", "privacy"];
const FILENAME = /^\d{4}-\d{2}-\d{2}\.mdx$/;

const versionsOf = (id) => {
  const files = readdirSync(path.join(contentDir, id)).filter((f) => f.endsWith(".mdx"));
  const stray = files.filter((f) => !FILENAME.test(f));
  if (stray.length) {
    throw new Error(
      `src/content/legal/${id}: ${stray.join(", ")} must be named YYYY-MM-DD.mdx ` +
        "(the filename is the document version)"
    );
  }
  if (!files.length) throw new Error(`src/content/legal/${id} has no dated .mdx document`);
  return files.map((f) => f.slice(0, -".mdx".length)).sort();
};

const entry = (id) =>
  [
    `  ${id}: {`,
    ...versionsOf(id).map(
      (v) => `    "${v}": () => import("@/content/legal/${id}/${v}.mdx"),`
    ),
    "  },",
  ].join("\n");

const source = `// AUTO-GENERATED by scripts/generate-legal-registry.mjs — do not edit.
// Regenerate with \`npm run legal:registry\` after adding a dated document.
import type { ComponentType } from "react";

type LegalDocumentLoader = () => Promise<{ default: ComponentType }>;

export const LEGAL_REGISTRY: Record<
  "terms" | "privacy",
  Record<string, LegalDocumentLoader>
> = {
${DOCUMENT_IDS.map(entry).join("\n")}
};
`;

let current = "";
try {
  current = readFileSync(outFile, "utf8");
} catch {
  // first run
}
if (current !== source) {
  writeFileSync(outFile, source);
  console.log("legal registry regenerated");
}
